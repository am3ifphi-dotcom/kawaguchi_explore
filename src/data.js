(function genTrees() {
  const rnd = mulberry(42);
  const clusters = [
    [-2, -14, 16, 8], [-32, -38, 10, 26], [55, -10, 62, 30], [-62, -16, 48, 30],
    [45, 55, 95, 62], [108, -30, 6, 30], [-108, -30, 6, 30],
  ];
  for (const [cx, cz, rx, rz] of clusters) {
    const n = Math.round((rx * rz) / 260) + 4;
    for (let i = 0; i < n; i++) {
      SITE.trees.push([cx + (rnd() * 2 - 1) * rx, cz + (rnd() * 2 - 1) * rz, 2.2 + rnd() * 2.2]);
    }
  }
})();

function mulberry(a) {
  return function () {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

